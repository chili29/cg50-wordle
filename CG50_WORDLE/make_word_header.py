#!/usr/bin/env python3
"""
Generate words.h from a newline-separated English word list.

Input defaults to words_alpha.txt (the dwyl/english-words list).
Only unique ASCII alphabetic words of exactly five letters are retained.
The output is sorted so main.c can validate guesses with binary search.
"""
from pathlib import Path
import re
import sys

source = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("words_alpha.txt")
output = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("words.h")

if not source.is_file():
    raise SystemExit(
        f"Missing {source}. Download a newline-separated English word list "
        "and run: python3 make_word_header.py words_alpha.txt"
    )

words = set()
for line in source.read_text(encoding="utf-8", errors="ignore").splitlines():
    word = line.strip().lower()
    if re.fullmatch(r"[a-z]{5}", word):
        words.add(word)

ordered = sorted(words)
if not ordered:
    raise SystemExit("No five-letter words found in the input file.")

with output.open("w", encoding="ascii", newline="\n") as f:
    f.write("/* Generated by make_word_header.py; do not edit by hand. */\n")
    f.write("#ifndef WORDS_H\n#define WORDS_H\n\n")
    f.write("static const char *words[] = {\n")
    for i in range(0, len(ordered), 8):
        f.write("    " + ", ".join(f'"{w}"' for w in ordered[i:i+8]))
        f.write(",\n")
    f.write("};\n\n")
    f.write("#endif\n")

print(f"Wrote {len(ordered):,} five-letter words to {output}")
